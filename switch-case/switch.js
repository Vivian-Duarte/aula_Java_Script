const opcao = 4

switch(opcao){
    case 1:
        const soma = 1+1
        console.log(`O valor da soma: ${soma}`)
        break

    case 2:
        const sub = 10 - 4
        console.log(`O valor da subtracao ${sub}`)
        break

    case 3:
        const mul = 4 * 68
        console.log(`O valor da multiplicacao e ${mul}`)
        break

    case 4:
        const div = 4 / 2
        console.log(`O valor da divisao e ${div}`)
        break
    
    default:
        console.log(`opcao invalida`)
        break
}   
